"""Regenerate figures/bits.tex: binary64 bit fields of 0.9, 0.1 and 1.0-0.9 (Chapter 7)."""
import struct, pathlib
def bits(x):
    h = struct.unpack('>Q', struct.pack('>d', x))[0]
    return format(h, '064b'), h
rows = [(0.9, '0.9'), (0.1, '0.1'), (1.0 - 0.9, '1.0 - 0.9')]
out = [r'% generated by gen_bits.py from struct.pack of the binary64 values', r'\begin{tikzpicture}[x=0.215cm,y=0.62cm]']
for r, (v, lab) in enumerate(rows):
    b, h = bits(v); y = -r * 1.55
    out.append(f'\\node[anchor=east,font=\\small\\ttfamily,text=fg] at (-0.6,{y+0.25:.2f}) {{{lab}}};')
    out.append(f'\\node[anchor=west,font=\\scriptsize\\ttfamily,text=org] at (64.6,{y+0.25:.2f}) {{0x{h:016X}}};')
    for i, ch in enumerate(b):
        col = 'red' if i == 0 else ('yel' if i < 12 else 'acc')
        fill = f'{col}!45!bg' if ch == '1' else 'codebg'
        out.append(f'\\draw[draw={col}!70!bg,fill={fill}] ({i},{y}) rectangle ++(1,0.5); \\node[font=\\tiny\\ttfamily,text=fg] at ({i+0.5},{y+0.25:.2f}) {{{ch}}};')
out.append(r'\draw[decorate,decoration={brace,amplitude=4pt},draw=red] (0,0.65) -- (1,0.65) node[midway,above left=5pt and -2pt,font=\scriptsize,text=red]{sign};')
out.append(r'\draw[decorate,decoration={brace,amplitude=4pt},draw=yel] (1,0.65) -- (12,0.65) node[midway,above=4pt,xshift=14pt,font=\scriptsize,text=yel]{exponent (11 bits, bias 1023)};')
out.append(r'\draw[decorate,decoration={brace,amplitude=4pt},draw=acc] (12,0.65) -- (64,0.65) node[midway,above=4pt,font=\scriptsize,text=acc]{fraction (52 bits; leading 1 implicit)};')
out.append(r'\end{tikzpicture}')
pathlib.Path(__file__).with_name('bits.tex').write_text('\n'.join(out) + '\n')
